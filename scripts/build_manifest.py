#!/usr/bin/env python3
"""Builds src/audio/manifest.json - every voice line, sound effect, ambience and
music cue in Ace Plays!. The game reads ids from it and scripts/generate_audio.mjs
uses the same entries (text / prompts) to generate audio with ElevenLabs."""
import json, os

E = []
def ace(i, text, group='common', tts=None):
    E.append(dict(id=i, kind='voice', speaker='ace', group=group, text=text, tts=tts or text, file=f'audio/voice/{i}.mp3'))
def nar(i, text, group='common', tts=None):
    E.append(dict(id=i, kind='voice', speaker='narrator', group=group, text=text, tts=tts or text, file=f'audio/voice/{i}.mp3'))
def sfx(i, prompt, dur=None, group='common', variants=None, volume=None):
    d = dict(id=i, kind='sfx', group=group, prompt=prompt, file=f'audio/sfx/{i}.mp3')
    if dur: d['duration'] = dur
    if variants: d['variants'] = variants
    if volume: d['volume'] = volume
    E.append(d)
def amb(i, prompt, group, dur=22, volume=None):
    d = dict(id=i, kind='ambience', group=group, prompt=prompt, duration=dur, loop=True, file=f'audio/ambience/{i}.mp3')
    if volume: d['volume'] = volume
    E.append(d)
def mus(i, prompt, group, dur=75, volume=None):
    d = dict(id=i, kind='music', group=group, prompt=prompt, duration=dur, loop=True, file=f'audio/music/{i}.mp3')
    if volume: d['volume'] = volume
    E.append(d)

